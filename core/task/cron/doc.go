// Package cron 提供 cron 表达式解析与定时任务调度器，可按调度表在独立 goroutine 中执行注册的任务。
//
// 基本用法：
//
//	c := cron.New()
//	c.AddFunc("30 * * * *", func() { ... })
//	c.AddFunc("@hourly", func() { ... })
//	c.Start()
//
// 调度器运行期间仍可继续添加任务；调用 Stop 仅停止后续调度，不会中断已经在执行的任务。
//
// 默认解析标准五段表达式，依次为：分钟（0-59）、小时（0-23）、日（1-31）、月（1-12 或 JAN-DEC）、
// 星期（0-6 或 SUN-SAT）；支持通配符 *、步长 /、列表逗号 ,、区间连字符 -，日与星期字段可用 ? 留空，
// 月份与星期取值大小写不敏感。配合 WithSeconds 可切换为首段包含秒字段的六段格式。
//
// 内置预定义调度：@yearly、@annually、@monthly、@weekly、@daily、@midnight、@hourly，
// 以及 @every <duration> 形式的固定间隔（时长由 time.ParseDuration 解析；间隔不扣除任务自身运行耗时）。
//
// 时区：默认使用机器本地时区，可通过 WithLocation 指定；单个表达式前缀可写 CRON_TZ=时区 或 TZ=时区
// 单独覆盖。夏令时跳空时段内到点的任务不会被触发。
//
// 包装器：通过 WithChain 为所有任务统一叠加自定义横切包装器（如异常恢复、并发互斥、日志记录）；
// 也可用 NewChain(...).Then(job) 单独包装某个任务。
//
// 线程安全：Cron 与调用代码并发运行，各方法在调用方保证调用顺序明确的前提下均做了内部同步，
// 可在运行期间并发添加、移除、查询条目。
